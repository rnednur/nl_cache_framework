    def add_template(self, template: CellTemplate):
        """Add a template to the library."""
        self.templates[template.name] = template
        logger.debug("Template added", name=template.name, type=template.cell_type.value)
    
    def get_template(self, name: str) -> Optional[CellTemplate]:
        """Get a template by name."""
        return self.templates.get(name)
    
    def list_templates(self, 
                      cell_type: Optional[CellType] = None,
                      tags: Optional[List[str]] = None) -> List[CellTemplate]:
        """
        List templates with optional filtering.
        
        Args:
            cell_type: Filter by cell type
            tags: Filter by tags (must have at least one matching tag)
            
        Returns:
            List of matching templates
        """
        templates = list(self.templates.values())
        
        if cell_type:
            templates = [t for t in templates if t.cell_type == cell_type]
        
        if tags:
            tag_set = set(tags)
            templates = [t for t in templates if tag_set.intersection(set(t.tags))]
        
        return templates
    
    def get_template_for_tool_type(self, tool_type: str) -> Optional[CellTemplate]:
        """
        Get the most appropriate template for a tool type.
        
        Args:
            tool_type: Type of tool (sql, api, script, etc.)
            
        Returns:
            Best matching template or None
        """
        # Direct mapping of tool types to template names
        tool_template_mapping = {
            "sql": "sql_query",
            "api": "api_request",
            "script": "python_script",
            "python": "python_script",
            "transform": "data_transform",
            "validation": "validation"
        }
        
        template_name = tool_template_mapping.get(tool_type.lower())
        if template_name:
            return self.get_template(template_name)
        
        # Fallback: look for templates with matching tags
        templates = self.list_templates(tags=[tool_type.lower()])
        if templates:
            return templates[0]
        
        # Default fallback
        return self.get_template("python_script")
    
    def render_template(self, 
                       template_name: str, 
                       context: Dict[str, Any]) -> Dict[str, Any]:
        """
        Render a template with context.
        
        Args:
            template_name: Name of template to render
            context: Variables for template substitution
            
        Returns:
            Rendered cell dictionary
            
        Raises:
            ValueError: If template not found or rendering fails
        """
        template = self.get_template(template_name)
        if not template:
            raise ValueError(f"Template not found: {template_name}")
        
        return template.render(context)