"""
Cell template system for notebook generation.
"""

import json
from typing import Dict, List, Any, Optional, Callable
from dataclasses import dataclass
from enum import Enum
import structlog

logger = structlog.get_logger()

class CellType(str, Enum):
    """Jupyter notebook cell types."""
    CODE = "code"
    MARKDOWN = "markdown"
    RAW = "raw"

@dataclass
class CellTemplate:
    """Template for generating notebook cells."""
    
    name: str
    cell_type: CellType
    template: str  # Template string with placeholders
    description: Optional[str] = None
    tags: List[str] = None
    variables: List[str] = None  # List of template variables
    
    def __post_init__(self):
        if self.tags is None:
            self.tags = []
        if self.variables is None:
            self.variables = []
    
    def render(self, context: Dict[str, Any]) -> Dict[str, Any]:
        """
        Render the template with given context.
        
        Args:
            context: Variables to substitute in template
            
        Returns:
            Jupyter notebook cell dictionary
        """
        try:
            # Substitute variables in template
            rendered_source = self.template.format(**context)
            
            # Split into lines for Jupyter format
            source_lines = rendered_source.split('\n')
            if source_lines and not source_lines[-1]:
                source_lines.pop()  # Remove empty last line
            
            # Add newlines to all but last line
            source = [line + '\n' for line in source_lines[:-1]]
            if source_lines:
                source.append(source_lines[-1])
            
            cell = {
                "cell_type": self.cell_type.value,
                "metadata": {
                    "template": self.name,
                    "tags": self.tags
                },
                "source": source
            }
            
            # Add execution fields for code cells
            if self.cell_type == CellType.CODE:
                cell["execution_count"] = None
                cell["outputs"] = []
            
            return cell
        
        except KeyError as e:
            raise ValueError(f"Missing template variable: {e}")
        except Exception as e:
            raise ValueError(f"Template rendering failed: {e}")

